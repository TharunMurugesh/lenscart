def q(v):
    """SQL literal."""
    if v is None or (isinstance(v, float) and v != v):  # None or NaN
        return "NULL"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, float):
        return f"{v:.2f}"
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def php_hash(pw: str) -> str:
    # bcrypt $2b$ and PHP's $2y$ are the same algorithm; PHP's password_verify expects $2y$.
    return "$2y$" + bcrypt.hashpw(pw.encode(), bcrypt.gensalt(10)).decode()[4:]


def price_for(rng, t):
    lo, hi = PRICE.get(t, (299, 1999))
    p = rng.uniform(lo, hi)
    return float(max(lo, int(round(p / 100.0)) * 100 - 1))  # e.g. 1299


def sample(df, rng):
    counts = df.articleType.value_counts()
    alloc = {t: max(MIN_PER_TYPE, int(round(N_PRODUCTS * c / len(df)))) for t, c in counts.items()}
    while sum(alloc.values()) > N_PRODUCTS:  # trim the largest types back to the total
        t = max(alloc, key=alloc.get)
        alloc[t] -= 1
    while sum(alloc.values()) < N_PRODUCTS:
        t = max(alloc, key=lambda k: counts[k] - alloc[k])
        alloc[t] += 1
    parts = [g.sample(n=min(alloc[t], len(g)), random_state=SEED) for t, g in df.groupby("articleType")]
    return pd.concat(parts).sort_values("id").reset_index(drop=True)


def write_labels_php():
    """site/inc/labels.php: the model's class names (from prepared/label_maps.json) for forms."""
    import json
    maps = json.loads((ROOT / "prepared" / "label_maps.json").read_text())
    lines = ["<?php", "// Generated by scripts/build_site_data.py from prepared/label_maps.json. Do not edit.",
             "const LABELS = ["]
    for head, m in maps.items():
        names = [n for n, _ in sorted(m.items(), key=lambda kv: kv[1])]
        lines.append(f"    '{head}' => [" + ", ".join("'" + n.replace("'", "\\'") + "'" for n in names) + "],")
    lines.append("];")
    (SITE / "inc" / "labels.php").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    rng = random.Random(SEED)
    df = pd.read_csv(ROOT / "prepared" / "split.csv")
    df = df[df.id.map(lambda i: (IMG_SRC / f"{i}.jpg").exists())]
    prods = sample(df, rng)
    assert prods.articleType.nunique() == 49, prods.articleType.nunique()

    IMG_DST.mkdir(parents=True, exist_ok=True)
    for i in prods.id:
        dst = IMG_DST / f"{i}.jpg"
        if not dst.exists():
            shutil.copyfile(IMG_SRC / f"{i}.jpg", dst)

    out = ["-- Generated by scripts/build_site_data.py (seed 42). Prices, stock, users, orders and",
           "-- views are SYNTHETIC demo data. Product names, images and labels come from the",
           "-- Fashion Product Images dataset (Kaggle, paramaggarwal).",
           "SET NAMES utf8mb4;", ""]

    rows, price_of = [], {}
    for r in prods.itertuples():
        price = price_for(rng, r.articleType)
        price_of[r.id] = price
        rows.append("(" + ",".join(q(v) for v in [
            int(r.id), r.productDisplayName if isinstance(r.productDisplayName, str) else r.articleType, r.articleType, r.baseColour, r.gender, r.usage,
            r.masterCategory, r.subCategory, price, rng.randint(0, 60), f"img/products/{r.id}.jpg"]) + ")")
    for k in range(0, len(rows), 250):
        out.append("INSERT INTO products (id,name,articleType,baseColour,gender,`usage`,masterCategory,"
                   "subCategory,price,stock,image) VALUES\n" + ",\n".join(rows[k:k + 250]) + ";")

    # users: 1 = admin, 2.. = demo customers
    out.append("INSERT INTO users (id,name,email,password_hash,role) VALUES")
    urows = [f"(1,'Admin',{q(ADMIN_EMAIL)},{q(php_hash(ADMIN_PASSWORD))},'admin')"]
    cust_hash = php_hash(CUSTOMER_PASSWORD)
    for u in range(N_CUSTOMERS):
        name = f"{FIRST[u]} {LAST[u % len(LAST)]}"
        email = f"{FIRST[u].lower()}.{LAST[u % len(LAST)].lower()}@example.com"
        urows.append(f"({u + 2},{q(name)},{q(email)},{q(cust_hash)},'user')")
    out.append(",\n".join(urows) + ";")

    # orders built as outfits: a seed product + 0-3 items of the same gender and usage, other types
    by_key = {k: g.id.tolist() for k, g in prods.groupby(["gender", "usage"])}
    ids = prods.id.tolist()
    meta = prods.set_index("id")
    orows, irows = [], []
    item_id = 1
    for o in range(1, N_ORDERS + 1):
        user = rng.randint(2, N_CUSTOMERS + 1)
        minutes = rng.randint(0, DAYS * 24 * 60)
        first = rng.choice(ids)
        g, u, t = meta.loc[first, "gender"], meta.loc[first, "usage"], meta.loc[first, "articleType"]
        pool = [i for i in by_key.get((g, u), []) if meta.loc[i, "articleType"] != t]
        basket = [first] + rng.sample(pool, min(len(pool), rng.choice([0, 1, 1, 2, 2, 3])))
        total = 0.0
        for pid in dict.fromkeys(basket):
            qty = rng.choice([1, 1, 1, 2])
            total += qty * price_of[pid]
            irows.append(f"({item_id},{o},{pid},{qty},{price_of[pid]:.2f})")
            item_id += 1
        status = "delivered" if minutes > 7 * 1440 else rng.choice(["placed", "shipped"])
        orows.append(f"({o},{user},{total:.2f},'{status}','Demo address, Bengaluru',"
                     f"DATE_SUB(NOW(), INTERVAL {minutes} MINUTE))")
    out.append("INSERT INTO orders (id,user_id,total,status,address,created_at) VALUES\n" + ",\n".join(orows) + ";")
    for k in range(0, len(irows), 500):
        out.append("INSERT INTO order_items (id,order_id,product_id,qty,price) VALUES\n"
                   + ",\n".join(irows[k:k + 500]) + ";")

    # views: each customer leans towards one type and colour
    vrows = []
    for user in range(2, N_CUSTOMERS + 2):
        fav = rng.choice(ids)
        ft, fc = meta.loc[fav, "articleType"], meta.loc[fav, "baseColour"]
        liked = [i for i in ids if meta.loc[i, "articleType"] == ft or meta.loc[i, "baseColour"] == fc]
        for _ in range(rng.randint(15, 40)):
            pid = rng.choice(liked) if rng.random() < 0.7 else rng.choice(ids)
            vrows.append(f"({user},{pid},DATE_SUB(NOW(), INTERVAL {rng.randint(0, DAYS * 1440)} MINUTE))")
    out.append("INSERT INTO views (user_id,product_id,ts) VALUES\n" + ",\n".join(vrows) + ";")

    write_labels_php()
    (SITE / "sql").mkdir(parents=True, exist_ok=True)
    (SITE / "sql" / "seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"products {len(prods)} ({prods.articleType.nunique()} types), images in {IMG_DST},"
          f" orders {N_ORDERS}, order items {len(irows)}, views {len(vrows)}")
    print("smallest types:", prods.articleType.value_counts().tail(3).to_dict())


if __name__ == "__main__":
    main()
